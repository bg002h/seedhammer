#!/usr/bin/env bash
# Vendor the Rust primary's shared policy-shape vectors (DESIGN_thresh_summary
# section 6, seedhammer I-1) into md/testdata/policy_shape_cases.json and write
# the provenance pin md/policy_shape_cases_test.go checks. Re-run on every
# re-pin.
#
#   scripts/vendor-policy-shape-cases.sh [/path/to/descriptor-mnemonic [<rev>]]
#
# The file is read from the COMMIT (`git show <rev>:<path>`, default HEAD), never
# from the working tree, so the pinned commit is exactly what was vendored: an
# uncommitted edit in the primary checkout cannot reach this repo under a
# commit that does not contain it.
#
# The file is generated by descriptor-mnemonic's
# crates/md-codec/tests/policy_shape_cases.rs and never edited by hand on either
# side. This repo takes the PRIMARY's copy (Rust-primary rule): the Go walk must
# agree with it, never the other way round.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="${1:-$HERE/../descriptor-mnemonic}"
REL="crates/md-codec/tests/fixtures/policy_shape/cases.json"
DST="$HERE/md/testdata/policy_shape_cases.json"
PIN="$HERE/md/testdata/policy_shape_cases.provenance.json"
REV="${2:-HEAD}"
commit=$(git -C "$SRC" rev-parse --verify "$REV^{commit}")
git -C "$SRC" cat-file -e "$commit:$REL" || { echo "no $REL at $commit" >&2; exit 2; }
git -C "$SRC" show "$commit:$REL" >"$DST"
python3 - "$PIN" "$commit" "$DST" "$REL" <<'PY'
import hashlib, json, sys, datetime
pin, commit, dst, rel = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
doc = {
  "_comment": [
    "PROVENANCE PIN for md/testdata/policy_shape_cases.json (seedhammer I-1, thresh k-of-n).",
    "Generated by scripts/vendor-policy-shape-cases.sh; never edited by hand.",
    "md/policy_shape_cases_test.go fails if the file's sha256 disagrees or the case count is not the one it asserts.",
  ],
  "repo": "descriptor-mnemonic",
  "remote": "git@github.com:bg002h/descriptor-mnemonic.git",
  "commit": commit,
  "read_from": "git show <commit>:<path>",
  "path": rel,
  "sha256": hashlib.sha256(open(dst, "rb").read()).hexdigest(),
  "recorded_at": datetime.date.today().isoformat(),
}
json.dump(doc, open(pin, "w"), indent=2); open(pin, "a").write("\n")
print("vendored %s, primary %s" % (rel, commit[:12]))
PY
