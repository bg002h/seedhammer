//go:embed sysw_composer_payload.bin
var syswComposerPayload string

// syswComposerDigest is what `me sysw show` prints for that blob, and therefore
// what the device shows an operator comparing it across the air gap. Pinned by
// TestSyswComposerPayloadMatchesItsDigest so the two cannot drift.
const syswComposerDigest = "dbe9 e774 e9a4 9231 0b62 626c 2b41 cf4b"

// syswComposerReader serves the composer payload. Same shape as
// syswCardsReader; a separate type for the same reason it was a separate type
// there — a walk chooses BETWEEN the blobs, and a single reader with a mutable
// blob would let one walk's choice leak into the next.
type syswComposerReader struct{ data []byte }

var _ sysw.Reader = syswComposerReader{}

func (r syswComposerReader) Probe() bool {
	return len(r.data) >= len(sysw.MAGIC) && [8]byte(r.data[:8]) == sysw.MAGIC
}

func (r syswComposerReader) Read() ([]byte, error) {
	if !r.Probe() {
		return nil, sysw.ErrBadMagic
	}
	out := make([]byte, len(r.data))
	copy(out, r.data)
	return out, nil
}
