// those screens, and before this blob no walk could reach them.
//
// WHY NOT EXTEND EITHER EXISTING BLOB. Their digests are pinned beside their
// own embeds AND photographed — the records blob in the published Load Payload
// journey, the cards blob in the cosigner-card walks. Editing one makes a
// published document wrong in the one way a reader cannot detect: it would
// still read as consistent.
//
// RECORD INVENTORY — stated here because not stating it is exactly how the
// FIRST blob's gap (three records, zero ClassMDMK) survived five review rounds.
// Five records, in this order:
//
//	@0   key:  master A, [73c5da0a/48'/0'/0'/2']xpub6DkFA…KFrf   (ClassKey)
//	@1   key:  master A, [73c5da0a/48'/0'/1'/2']xpub6Dzhy…d6Vk   (ClassKey)
//	@2   hash: abababab…abababab                                 (ClassHash)
//	@3   now:  1788220800,905000                                 (ClassNow)
//	@4   ClassMnemonic — master B
//
// WHAT EACH RECORD IS FOR. Deleting any line strands the screen beside it:
//
//	@0, @1  the composer's key SOURCES: the seating picker's two rows, and the
//	        2-of-2 path they fill. They are ONE MASTER AT TWO ACCOUNTS on
//	        purpose — that is what fires §8g's same-seed warning at the mapping
//	        review ("Slots @0 and @1 are the same seed…"), a screen no other
//	        emulator fixture reaches. Read as a defect it is a false alarm; it
//	        is the fixture's purpose.
//	@2      the hash-lock picker's `hash 1  abababab..abababab` row, and with
//	        it the §8i preimage modal, which is drawn on the way through.
//	@3      the pack time. Present so the composer HAS a bound; the fixture's
//	        lock is RELATIVE (12960 blocks), whose echo carries no bound line,
//	        so this record is what an ABSOLUTE lock's echo would draw from.
//	@4      the seed slot @2 is seated from, through `Type a seed` → `FROM
//	        PAYLOAD`. A SECOND master, so the keyed policy spans two, and the
//	        device seats it at ITS OWN account 0' rather than at md's
//	        lowest-free 2' — the divergence the keyed arm's oracle is minted
//	        against.
//
// PROVENANCE. Generated by `go run ./cmd/buildpayloadcomposer | me sysw pack
// --no-passphrase --out <this file's .bin>`, through the device's own
// derivation path (bip39.MnemonicSeed → hdkeychain.NewMaster → bip32.Derive →
