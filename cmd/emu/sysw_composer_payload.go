// with that command; do not hand-edit.
//
// TEST MATERIAL, public by construction: masters A and B are BIP-39's own
// published vectors (`abandon…about`, `legal winner…yellow`) and the hashlock
// digest is a repeating byte, not the hash of anything anybody holds. The
// payload is UNSEALED, so a passphrase protects nothing here — there is
// nothing here to protect. Never put funds behind them.
